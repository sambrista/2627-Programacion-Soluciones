public class EjemploChar {
    public void main() {
        char letra = 'A'; // 65
        char letra2 = 'b';
        System.out.println(letra);
        System.out.println(letra + 1);
        System.out.println((char) (letra + 1));
        System.out.println(letra > 96);
        System.out.println(letra >= 'A');
        System.out.println(letra2 > 96);
    }
}